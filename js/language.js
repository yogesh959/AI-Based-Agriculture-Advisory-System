const textState = new WeakMap();
const attributeState = new WeakMap();
const translatableAttributes = ["placeholder", "title", "aria-label", "alt"];
let selectedLanguage = "English";

function translateValue(value, language) {
    const dictionary = translations[language];
    if (!dictionary) return value;

    let translated = value;
    Object.entries(dictionary)
        .sort((left, right) => right[0].length - left[0].length)
        .forEach(([source, target]) => {
            translated = translated.split(source).join(target);
        });
    return translated;
}

function translateTextNode(node) {
    const currentValue = node.nodeValue;
    let state = textState.get(node);
    if (!state || currentValue !== state.translated) {
        state = { original: currentValue, translated: currentValue };
        textState.set(node, state);
    }

    const translated = translateValue(state.original, selectedLanguage);
    state.translated = translated;
    if (node.nodeValue !== translated) node.nodeValue = translated;
}

function translateAttribute(element, attribute) {
    const currentValue = element.getAttribute(attribute);
    if (currentValue === null) return;

    let states = attributeState.get(element);
    if (!states) {
        states = new Map();
        attributeState.set(element, states);
    }

    let state = states.get(attribute);
    if (!state || currentValue !== state.translated) {
        state = { original: currentValue, translated: currentValue };
        states.set(attribute, state);
    }

    const translated = translateValue(state.original, selectedLanguage);
    state.translated = translated;
    if (currentValue !== translated) element.setAttribute(attribute, translated);
}

function translateElement(element) {
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            const parentTag = node.parentElement?.tagName;
            return ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parentTag)
                ? NodeFilter.FILTER_REJECT
                : NodeFilter.FILTER_ACCEPT;
        }
    });

    while (walker.nextNode()) translateTextNode(walker.currentNode);
    if (element.nodeType === Node.ELEMENT_NODE) {
        translatableAttributes.forEach((attribute) => translateAttribute(element, attribute));
        element.querySelectorAll("*").forEach((child) => {
            translatableAttributes.forEach((attribute) => translateAttribute(child, attribute));
        });
    }
}

function applyLanguage(language) {
    selectedLanguage = ["Hindi", "Telugu"].includes(language) ? language : "English";
    document.documentElement.lang = selectedLanguage === "English"
        ? "en"
        : selectedLanguage === "Hindi" ? "hi" : "te";
    translateElement(document.documentElement);
    try {
        localStorage.setItem("agriLanguage", selectedLanguage);
    } catch (error) {
        console.warn("Language preference could not be saved.");
    }
    document.dispatchEvent(new CustomEvent("agri-language-change", {
        detail: { language: selectedLanguage }
    }));
}

function initializeLanguage() {
    const selector = document.getElementById("language");
    if (!selector) return;

    document.querySelectorAll("select option").forEach((option) => {
        if (!option.hasAttribute("value")) option.value = option.textContent.trim();
    });

    let savedLanguage = "English";
    try {
        savedLanguage = localStorage.getItem("agriLanguage") || "English";
    } catch (error) {
        savedLanguage = "English";
    }

    selector.value = ["English", "Hindi", "Telugu"].includes(savedLanguage)
        ? savedLanguage
        : "English";
    selector.addEventListener("change", () => applyLanguage(selector.value));
    applyLanguage(selector.value);

    const observer = new MutationObserver((mutations) => {
        mutations.forEach((mutation) => {
            if (mutation.type === "characterData") {
                translateTextNode(mutation.target);
            }
            mutation.addedNodes?.forEach((node) => {
                if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
                else if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
            });
        });
    });
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
}

window.translateForCurrentLanguage = (value) => translateValue(value, selectedLanguage);

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initializeLanguage, { once: true });
} else {
    initializeLanguage();
}